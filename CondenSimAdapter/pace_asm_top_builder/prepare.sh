#modify coordinate file
sed -e "s/N   NMA/N   NH2/g" -e "s/H   NMA/H1  NH2/g" -e "s/CA  NMA/H2  NH2/g"  "$1"-pace-resid.pdb > "$1"-pace-resid_a.pdb || exit
mv "$1"-pace-resid_a.pdb "$1"-pace-resid.pdb
