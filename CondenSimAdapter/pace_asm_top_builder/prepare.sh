python "$SDIR"add-cap.py "$1"_a.pdb Cter > "$1"-Ccap.pdb
#pdb2gmx
gmx pdb2gmx -f "$1"-Ccap.pdb -o "$1"-pace.pdb -p draft.top -ff pace-asm -ter -ignh <<EOF
1
0
1
EOF
#renumber residues
python "$SDIR"change_resid.py "$1"-pace.pdb > "$1"-pace-resid.pdb || exit
