python "$SDIR"add-cap.py "$1"_a.pdb both > "$1"-cap.pdb
#pdb2gmx
gmx pdb2gmx -f "$1"-cap.pdb -o "$1"-pace.pdb -p draft.top -ff pace-asm -ter -ignh <<EOF
1
1
1
EOF
